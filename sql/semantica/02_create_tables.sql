-- Tablas del repositorio semantico
-- Nota: los catalogos describen el DWH; no modifican sus tablas fisicas.

CREATE TABLE IF NOT EXISTS semantic.sem_tablas (
    tabla_id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_tabla         VARCHAR(100) NOT NULL UNIQUE,
    nombre_negocio       VARCHAR(150) NOT NULL,
    descripcion_negocio  TEXT,
    tipo_tabla           VARCHAR(20) NOT NULL
                         CHECK (tipo_tabla IN ('DIMENSION','FACT')),
    dominio_negocio      VARCHAR(50),
    granularidad         TEXT,
    periodicidad         VARCHAR(30),
    entidad_principal    VARCHAR(50),
    fecha_referencia     VARCHAR(100),
    alias_negocio        JSONB NOT NULL DEFAULT '[]'::jsonb,
    preguntas_soportadas JSONB NOT NULL DEFAULT '[]'::jsonb,
    restricciones        TEXT,
    activo               BOOLEAN NOT NULL DEFAULT TRUE,
    version_metadata     INTEGER NOT NULL DEFAULT 1,
    fecha_actualizacion  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS semantic.sem_columnas (
    columna_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tabla_id              BIGINT NOT NULL REFERENCES semantic.sem_tablas(tabla_id),
    nombre_columna        VARCHAR(100) NOT NULL,
    tipo_dato_fisico      VARCHAR(80) NOT NULL,
    tipo_dato_semantico   VARCHAR(50),
    nombre_negocio        VARCHAR(150),
    descripcion_negocio   TEXT,
    sinonimos             JSONB NOT NULL DEFAULT '[]'::jsonb,
    dominio_negocio       VARCHAR(50),
    concepto_negocio      VARCHAR(100),
    es_clave              BOOLEAN NOT NULL DEFAULT FALSE,
    tipo_clave            VARCHAR(10) CHECK (tipo_clave IN ('PK','FK','UK')),
    tabla_referenciada    VARCHAR(100),
    campo_referenciado    VARCHAR(100),
    es_nullable           BOOLEAN,
    regla_transformacion  TEXT,
    regla_validacion      TEXT,
    sensibilidad          VARCHAR(30),
    ejemplos_valores      JSONB NOT NULL DEFAULT '[]'::jsonb,
    sql_generation_hints  TEXT,
    nivel_confianza       VARCHAR(20) NOT NULL DEFAULT 'PROPUESTO'
                          CHECK (nivel_confianza IN ('CONFIRMADO','PROPUESTO','PENDIENTE')),
    activo                BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_actualizacion   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (tabla_id, nombre_columna)
);

CREATE TABLE IF NOT EXISTS semantic.sem_metricas (
    metrica_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_metrica          VARCHAR(50) NOT NULL UNIQUE,
    nombre_metrica          VARCHAR(150) NOT NULL,
    descripcion             TEXT,
    tabla_origen            BIGINT NOT NULL REFERENCES semantic.sem_tablas(tabla_id),
    campo_origen            VARCHAR(100),
    formula_sql             TEXT,
    agregacion              VARCHAR(30),
    tipo_metrica            VARCHAR(30)
                            CHECK (tipo_metrica IN ('ADITIVA','SEMI_ADITIVA','NO_ADITIVA','DERIVADA')),
    unidad_medida           VARCHAR(30),
    dimensiones_permitidas  JSONB NOT NULL DEFAULT '[]'::jsonb,
    filtros_obligatorios    JSONB NOT NULL DEFAULT '[]'::jsonb,
    sinonimos               JSONB NOT NULL DEFAULT '[]'::jsonb,
    comportamiento_temporal VARCHAR(30),
    restricciones           TEXT,
    nivel_confianza         VARCHAR(20) NOT NULL DEFAULT 'PROPUESTO'
                            CHECK (nivel_confianza IN ('CONFIRMADO','PROPUESTO','PENDIENTE')),
    activo                  BOOLEAN NOT NULL DEFAULT TRUE,
    version_metadata        INTEGER NOT NULL DEFAULT 1,
    fecha_actualizacion     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS semantic.sem_reglas_negocio (
    regla_id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_regla         VARCHAR(50) NOT NULL UNIQUE,
    nombre_regla         VARCHAR(150) NOT NULL,
    descripcion          TEXT,
    ambito               VARCHAR(30) NOT NULL
                         CHECK (ambito IN ('GLOBAL','TABLA','COLUMNA','METRICA')),
    tabla_id             BIGINT REFERENCES semantic.sem_tablas(tabla_id),
    campo                VARCHAR(100),
    codigo_metrica       VARCHAR(50) REFERENCES semantic.sem_metricas(codigo_metrica),
    tipo_regla           VARCHAR(30),
    condicion            TEXT,
    instruccion_sql      TEXT,
    prioridad            INTEGER NOT NULL DEFAULT 100,
    obligatoriedad       VARCHAR(20) NOT NULL DEFAULT 'OBLIGATORIA'
                         CHECK (obligatoriedad IN ('OBLIGATORIA','RECOMENDADA')),
    mensaje_error        TEXT,
    nivel_confianza      VARCHAR(20) NOT NULL DEFAULT 'PROPUESTO'
                         CHECK (nivel_confianza IN ('CONFIRMADO','PROPUESTO','PENDIENTE')),
    activo               BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_actualizacion  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS semantic.sem_relaciones (
    relacion_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_relacion      VARCHAR(150) NOT NULL UNIQUE,
    tabla_origen         BIGINT NOT NULL REFERENCES semantic.sem_tablas(tabla_id),
    campo_origen         VARCHAR(100) NOT NULL,
    tabla_destino        BIGINT NOT NULL REFERENCES semantic.sem_tablas(tabla_id),
    campo_destino        VARCHAR(100) NOT NULL,
    cardinalidad         VARCHAR(10)
                         CHECK (cardinalidad IN ('1:1','1:N','N:1','N:M')),
    tipo_join            VARCHAR(20) NOT NULL DEFAULT 'INNER JOIN'
                         CHECK (tipo_join IN ('INNER JOIN','LEFT JOIN')),
    condicion_join       TEXT,
    relacion_validada    BOOLEAN NOT NULL DEFAULT FALSE,
    descripcion_negocio  TEXT,
    restricciones        TEXT,
    activo               BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_actualizacion  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_sem_columnas_tabla
    ON semantic.sem_columnas(tabla_id);
CREATE INDEX IF NOT EXISTS idx_sem_columnas_sinonimos
    ON semantic.sem_columnas USING GIN(sinonimos);
CREATE INDEX IF NOT EXISTS idx_sem_metricas_tabla
    ON semantic.sem_metricas(tabla_origen);
CREATE INDEX IF NOT EXISTS idx_sem_reglas_tabla
    ON semantic.sem_reglas_negocio(tabla_id);
CREATE INDEX IF NOT EXISTS idx_sem_relaciones_origen
    ON semantic.sem_relaciones(tabla_origen);
CREATE INDEX IF NOT EXISTS idx_sem_relaciones_destino
    ON semantic.sem_relaciones(tabla_destino);
